using System;

namespace Dex.MassTransit.Rabbit;

/// <summary>
/// Маскирует тело сообщения перед записью в лог об упавшей обработке.
/// </summary>
/// <remarks>
/// Берётся из контейнера консьюмера; пакет его не регистрирует, готовая реализация — <see cref="SensitiveNamesMessageDataMasker"/>.
/// Консьюмер, созданный не контейнером (фабрикой или экземпляром), маскировщика не получает и пишет тело как есть.
/// Вход приходит с запасом над лимитом записи, чтобы место, освобождённое маской, досталось следующим полям; результат
/// пакет не режет и метку усечения не ставит. Сбой маскировщика тело не открывает: вместо него в запись уходит маркер.
/// </remarks>
public interface IMessageDataMasker
{
    /// <summary>
    /// Отдаёт тело для лога с замаскированными значениями, не длиннее <paramref name="limit"/> байт UTF-8.
    /// </summary>
    /// <param name="json">Тело в JSON, UTF-8, или его начало; обрез идёт по границе символа.</param>
    /// <param name="isComplete">Ложь — передано только начало тела, последний токен может быть оборван.</param>
    /// <param name="limit">Предельный размер результата в байтах UTF-8; неполный результат маскировщик помечает сам.</param>
    string Mask(ReadOnlySpan<byte> json, bool isComplete, int limit);
}