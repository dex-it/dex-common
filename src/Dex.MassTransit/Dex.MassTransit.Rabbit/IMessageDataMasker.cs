using System;

namespace Dex.MassTransit.Rabbit;

/// <summary>
/// Маскирует тело сообщения перед записью в лог об упавшей обработке.
/// </summary>
/// <remarks>
/// Берётся из контейнера консьюмера; пакет его не регистрирует, готовая реализация — <see cref="SensitiveNamesMessageDataMasker"/>.
/// Консьюмер, созданный не контейнером (фабрикой или экземпляром), маскировщика не получает и пишет тело как есть, если
/// endpoint не открывает scope сообщения (<c>UseMessageScope</c>).
/// Вход приходит с запасом над лимитом записи, чтобы место, освобождённое маской, досталось следующим полям. Потолок записи
/// держит пакет: результат длиннее лимита он обрезает сам. Сбой маскировщика тело не открывает: вместо него в запись уходит маркер.
/// </remarks>
public interface IMessageDataMasker
{
    /// <summary>
    /// Отдаёт тело для лога с замаскированными значениями, не длиннее <paramref name="limit"/> байт UTF-8 и метки усечения; <see langword="null"/> — пустое тело.
    /// </summary>
    /// <param name="json">Тело в JSON, UTF-8, или его начало; обрез идёт по границе символа.</param>
    /// <param name="isComplete">Ложь — передано только начало тела: последний токен может быть оборван, и оборванное значение не пишется даже началом.</param>
    /// <param name="limit">Предельный размер результата в байтах UTF-8; неполный результат в пределах лимита маскировщик помечает сам.</param>
    string? Mask(ReadOnlySpan<byte> json, bool isComplete, int limit);
}